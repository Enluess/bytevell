function inject(lang) {
  const filePath = `client/messages/${lang}.json`;
  let data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  if (!data.Admin) data.Admin = {};
  if (!data.Admin.Dashboard) data.Admin.Dashboard = {};
  if (!data.Admin.Invoices) data.Admin.Invoices = {};
  if (!data.Admin.Services) data.Admin.Services = {};
  if (!data.Admin.Tickets) data.Admin.Tickets = {};
  if (!data.Admin.Users) data.Admin.Users = {};
  if (!data.Panel) data.Panel = {};
  if (!data.Panel.Header) data.Panel.Header = {};

  for (const k of missingKeys) {
    const parts = k.split('.');
    const translation = translations[lang][k];
    
    let current = data;
    for (let i = 0; i < parts.length - 1; i++) {
      if (!current[parts[i]]) current[parts[i]] = {};
      current = current[parts[i]];
    }
    
    // Sadece henüz yoksa veya İngilizce/Almancada Türkçesi kalmışsa (placeholder vs) ezelim
    current[parts[parts.length - 1]] = translation;
  }
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2));
}

